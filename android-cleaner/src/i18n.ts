const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, es };

export function translate(
  language: Language,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const template = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] !== undefined ? String(vars[name]) : `{${name}}`,
  );
}

export function categoryTranslation(
  language: Language,
  id: string,
  field: "label" | "desc",
  fallback: string,
): string {
  const key = `category.${id}.${field}` as TranslationKey;
  return dictionaries[language][key] ?? fallback;
}

export function translateWarning(language: Language, warning: string): string {
  if (language === "en") return warning;
  const exact: Record<string, string> = {
    "WhatsApp media will disappear from chats. Databases and documents are kept.":
      "La multimedia de WhatsApp desaparecerá de los chats. Las bases de datos y los documentos se conservan.",
    "Telegram media will disappear from chats. Documents and files are kept.":
      "La multimedia de Telegram desaparecerá de los chats. Los documentos y archivos se conservan.",
    "Duplicate cleanup keeps one copy of each hash group.":
      "La limpieza de duplicados conserva una copia de cada grupo de hash.",
  };
  if (exact[warning]) return exact[warning];
  const cache = warning.match(/^App cache trim will run after deletion, targeting about (.*) GB\.$/);
  if (cache) {
    return `La limpieza de caché se ejecutará después de eliminar, con un objetivo de aproximadamente ${cache[1]} GB.`;
  }
  return warning;
}
